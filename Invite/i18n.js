export function translateText(value, language) {
  if (!Object.prototype.hasOwnProperty.call(translations, language)) return value;
  const key = String(value).trim();
  if (translations[language][key]) return String(value).replace(key, translations[language][key]);

  const undecorated = key.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, '').trim();
  if (undecorated !== key && translations[language][undecorated]) {
    return String(value).replace(undecorated, translations[language][undecorated]);
  }

  const salutation = key.match(/^Dear\s+(.+)$/i);
  if (salutation) {
    const greeting = language === 'bn' ? 'প্রিয়' : language === 'hi' ? 'प्रिय' : 'محترم';
    return `${greeting} ${salutation[1]}`;
  }

  
  // Preserve initial monograms like "A&T", "A & T", "AT", "TA"
  if (/^[A-Z](?:\s*&(?:amp;)?\s*|\s+)[A-Z]$/.test(key) || /^[A-Z]{2}$/.test(key)) {
    return key;
  }

  // Handle Family Surname line: "The [Name] & [Name] Families" -> "[Name] ও [Name] পরিবার"
  const famMatch = key.match(/^The\s+([A-Za-z]+)(?:\s+(?:&amp;|&|and)\s+([A-Za-z]+))?\s+Families$/i);
  if (famMatch) {
    const f1 = famMatch[1];
    const f2 = famMatch[2];
    if (language === 'bn') return f2 ? `${f1} ও ${f2} পরিবার` : `${f1} পরিবার`;
    if (language === 'hi') return f2 ? `${f1} और ${f2} परिवार` : `${f1} परिवार`;
    if (language === 'ur') return f2 ? `${f1} اور ${f2} خاندان` : `${f1} خاندان`;
  }

  // Handle Day Headings: "Day One · Friday, 04 Dec 2026" / "DAY 1 · Fri, 04 Dec 2026"
  const dayHeadingMatch = key.match(/^(?:DAY|Day)\s+(ONE|TWO|THREE|FOUR|FIVE|One|Two|Three|Four|Five|\d+)\s*·\s*(.+)$/i);
  if (dayHeadingMatch) {
    const ordMap = {
      bn: { 'One': 'প্রথম', 'Two': 'দ্বিতীয়', 'Three': 'তৃতীয়', 'Four': 'চতুর্থ', 'Five': 'পঞ্চম', '1': '১ম', '2': '২য়', '3': '৩য়', '4': '৪র্থ', '5': '৫ম' },
      hi: { 'One': 'प्रथम', 'Two': 'द्वितीय', 'Three': 'तृतीय', 'Four': 'चतुर्थ', 'Five': 'पंचम', '1': 'पहला', '2': 'दूसरा', '3': 'तीसरा', '4': 'चौथा', '5': 'पाँचवाँ' },
      ur: { 'One': 'پہلا', 'Two': 'دوسرا', 'Three': 'تیسرا', 'Four': 'چوتھا', 'Five': 'پانچواں', '1': 'پہلا', '2': 'دوسرا', '3': 'تیسرا', '4': 'چوتھا', '5': 'پانچواں' }
    };
    const ordKey = dayHeadingMatch[1].charAt(0).toUpperCase() + dayHeadingMatch[1].slice(1).toLowerCase();
    const ordTranslated = ordMap[language]?.[ordKey] || ordMap[language]?.[dayHeadingMatch[1]] || dayHeadingMatch[1];
    const restTranslated = translateText(dayHeadingMatch[2], language);
    const dayWord = language === 'bn' ? 'দিন' : language === 'hi' ? 'दिन' : 'دن';
    return `${dayWord} ${ordTranslated} · ${restTranslated}`;
  }

  // Handle month year: "December 2026" / "Dec 2026"
  const monthYearMatch = key.match(/^([A-Za-z]{3,9})\s+(\d{4})$/);
  if (monthYearMatch) {
    const monTrans = translateText(monthYearMatch[1], language);
    const yr = monthYearMatch[2];
    const bnDigs = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
    const urDigs = ['۰','۱','۲','۳','۴','۵','۶','۷','۸','۹'];
    if (language === 'bn') return `${monTrans} ${yr.replace(/\d/g, d => bnDigs[d])}`;
    if (language === 'ur') return `${monTrans} ${yr.replace(/\d/g, d => urDigs[d])}`;
    return `${monTrans} ${yr}`;
  }

  // Handle day and time: "Saturday, 7:00 PM"
  const dayTimeMatch = key.match(/^([A-Za-z]+),\s*(\d{1,2}:\d{2}\s*(?:AM|PM))$/i);
  if (dayTimeMatch) {
    const dayTrans = translateText(dayTimeMatch[1], language);
    const timeTrans = translateText(dayTimeMatch[2], language);
    return `${dayTrans}, ${timeTrans}`;
  }

  // Handle time patterns like "at 7:00 PM" / "7:00 PM" / "11:00 AM" / "⏰ 11:00 AM"
  const timeOnlyMatch = key.match(/^(?:at\s+|⏰\s*)?(\d{1,2}(?::|\.\s*)\d{2}\s*(?:AM|PM))$/i);
  if (timeOnlyMatch) {
    const timeRaw = timeOnlyMatch[1].replace(/\.\s*/, ':');
    const [hStr, mStrMer] = timeRaw.split(':');
    const h = parseInt(hStr, 10);
    const [mStr, mer] = mStrMer.trim().split(/\s+/);
    const isPm = mer?.toUpperCase() === 'PM';
    const prefix = key.startsWith('⏰') ? '⏰ ' : '';
    if (language === 'bn') {
      const bnDigs = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
      const toBnDigits = s => String(s).replace(/\d/g, d => bnDigs[d]);
      const per = isPm ? (h === 12 || h < 4 ? 'দুপুর' : h < 7 ? 'বিকেল' : 'সন্ধ্যা') : (h < 5 ? 'রাত' : h < 12 ? 'সকাল' : 'দুপুর');
      return `${prefix}${per} ${toBnDigits(h)}:${toBnDigits(mStr)}`;
    }
    if (language === 'hi') {
      const per = isPm ? (h === 12 || h < 4 ? 'दोपहर' : h < 7 ? 'शाम' : 'रात') : (h < 5 ? 'रात' : h < 12 ? 'सुबह' : 'दोपहर');
      return `${prefix}${per} ${h}:${mStr} बजे`;
    }
    if (language === 'ur') {
      const urDigs = ['۰','۱','۲','۳','۴','۵','۶','۷','۸','۹'];
      const toUrDigits = s => String(s).replace(/\d/g, d => urDigs[d]);
      const per = isPm ? (h === 12 || h < 4 ? 'دوپہر' : h < 7 ? 'شام' : 'رات') : (h < 5 ? 'رات' : h < 12 ? 'صبح' : 'دوپہر');
      return `${prefix}${per} ${toUrDigits(h)}:${toUrDigits(mStr)} بجے`;
    }
  }

  // Handle date badges: "4 Dec", "5 Dec 2026 (Sat)", "📅 4 Dec 2026 (Fri)"
  const dateBadgeMatch = key.match(/^(📅\s*)?(\d{1,2})\s+([A-Za-z]{3,9})(?:\s+(\d{4}))?(?:\s*\(([A-Za-z]{3,9})\))?$/);
  if (dateBadgeMatch) {
    const icon = dateBadgeMatch[1] || '';
    const day = dateBadgeMatch[2];
    const mon = dateBadgeMatch[3];
    const year = dateBadgeMatch[4] || '';
    const wk = dateBadgeMatch[5] || '';
    const monTrans = translateText(mon, language);
    const wkTrans = wk ? translateText(wk, language) : '';
    const bnDigs = ['০','১','২','৩','৪','৫','৬','৭','৮','৯'];
    const urDigs = ['۰','۱','۲','۳','۴','۵','۶','۷','۸','۹'];
    if (language === 'bn') {
      const bDay = day.replace(/\d/g, d => bnDigs[d]);
      const bYear = year ? ' ' + year.replace(/\d/g, d => bnDigs[d]) : '';
      const bWk = wkTrans ? ` (${wkTrans})` : '';
      return `${icon}${bDay} ${monTrans}${bYear}${bWk}`;
    }
    if (language === 'ur') {
      const uDay = day.replace(/\d/g, d => urDigs[d]);
      const uYear = year ? ' ' + year.replace(/\d/g, d => urDigs[d]) : '';
      const uWk = wkTrans ? ` (${wkTrans})` : '';
      return `${icon}${uDay} ${monTrans}${uYear}${uWk}`;
    }
    if (language === 'hi') {
      const hYear = year ? ' ' + year : '';
      const hWk = wkTrans ? ` (${wkTrans})` : '';
      return `${icon}${day} ${monTrans}${hYear}${hWk}`;
    }
  }

  // Handle "Saturday, 05 December 2026 · 7:00 PM"
  if (key.includes('·') && /(?:January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Oct|Nov|Dec)/i.test(key)) {
    const parts = key.split('·');
    const transParts = parts.map(p => translateText(p.trim(), language));
    return transParts.join(' · ');
  }

  const invitation = key.match(/^Invitation for (\d+) guests?$/i);
  if (invitation) {
    const count = new Intl.NumberFormat(language).format(Number(invitation[1]));
    const suffix = language === 'bn' ? 'জনের আমন্ত্রণ' : language === 'hi' ? 'अतिथियों का निमंत्रण' : 'مہمانوں کے لیے دعوت';
    return `${count} ${suffix}`;
  }

  const attendeeLimit = key.match(/^Number attending \(up to (\d+)\)$/);
  if (attendeeLimit) {
    const count = new Intl.NumberFormat(language).format(Number(attendeeLimit[1]));
    if (language === 'bn') return `কতজন আসবেন (সর্বোচ্চ ${count})`;
    if (language === 'hi') return `कितने अतिथि आएंगे (अधिकतम ${count})`;
    return `شرکت کرنے والے مہمان (زیادہ سے زیادہ ${count})`;
  }

  const englishMonths = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  const monthIndex = englishMonths.findIndex(month => month.toLowerCase() === key.toLowerCase() || month.slice(0, 3).toLowerCase() === key.toLowerCase());
  if (monthIndex >= 0) return new Intl.DateTimeFormat(language, { month: 'long' }).format(new Date(2020, monthIndex, 1));

  const englishWeekdays = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const weekdayIndex = englishWeekdays.findIndex(weekday => weekday.toLowerCase() === key.toLowerCase());
  if (weekdayIndex >= 0) return new Intl.DateTimeFormat(language, { weekday: 'long' }).format(new Date(2020, 5, 7 + weekdayIndex));

  const ordinal = key.match(/^(\d{1,2})(?:st|nd|rd|th)$/i);
  if (ordinal) return new Intl.NumberFormat(language).format(Number(ordinal[1]));

  if (/^\d+$/.test(key)) return new Intl.NumberFormat(language).format(Number(key));

  const dateMatch = key.match(/^\d{4}-\d{2}-\d{2}$/);
  if (dateMatch) {
    const date = new Date(`${key}T12:00:00`);
    if (!Number.isNaN(date.getTime())) return new Intl.DateTimeFormat(language, { day: 'numeric', month: 'long', year: 'numeric' }).format(date);
  }

  const writtenDate = key.match(/^(?:(Sunday|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday),?\s+)?(\d{1,2})(?:st|nd|rd|th)?[\s/-]+([A-Za-z]+)[\s,/-]+(\d{4})$/i)
    || key.match(/^(Sunday|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday),\s+([A-Za-z]+)\s+(\d{1,2})(?:st|nd|rd|th)?,?\s+(\d{4})$/i);
  if (writtenDate) {
    const monthNames = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];
    const isMonthFirst = /^[A-Za-z]+$/.test(writtenDate[2]);
    const weekday = writtenDate[1];
    const day = Number(isMonthFirst ? writtenDate[3] : writtenDate[2]);
    const monthText = isMonthFirst ? writtenDate[2] : writtenDate[3];
    const year = Number(writtenDate[4]);
    const month = monthNames.indexOf(monthText.toLowerCase().slice(0, 3));
    if (month >= 0) {
      const date = new Date(year, month, day);
      if (date.getFullYear() === year && date.getMonth() === month && date.getDate() === day) {
        const options = { day: 'numeric', month: 'long', year: 'numeric' };
        if (weekday) options.weekday = 'long';
        return new Intl.DateTimeFormat(language, options).format(date);
      }
    }
  }

  const localizedDate = key
    .replace(/[০-৯]/g, digit => String(digit.charCodeAt(0) - 0x09e6))
    .replace(/[०-९]/g, digit => String(digit.charCodeAt(0) - 0x0966))
    .replace(/[٠-٩]/g, digit => String(digit.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, digit => String(digit.charCodeAt(0) - 0x06f0))
    .match(/^(?:[^,\s]+[،,]\s*)?(\d{1,2})\s+([^،,\s]+)[،,]?\s+(\d{4})$/u);
  if (localizedDate) {
    const sourceMonth = localizedDate[2].replace(/[^\p{L}]/gu, '').toLocaleLowerCase();
    const sourceLocales = ['en-US', 'bn-BD', 'hi-IN', 'ur-PK'];
    const monthIndex = Array.from({ length: 12 }, (_, index) => index).find(index =>
      sourceLocales.some(locale => {
        const month = new Intl.DateTimeFormat(locale, { month: 'long' })
          .format(new Date(2020, index, 1))
          .replace(/[^\p{L}]/gu, '')
          .toLocaleLowerCase();
        return month === sourceMonth;
      })
    );
    if (monthIndex !== undefined) {
      const day = Number(localizedDate[1]);
      const year = Number(localizedDate[3]);
      const date = new Date(year, monthIndex, day);
      if (date.getFullYear() === year && date.getMonth() === monthIndex && date.getDate() === day) {
        return new Intl.DateTimeFormat(language, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }).format(date);
      }
    }
  }

  return value;
}


export function localizeHtml(html, language) {
  if (!Object.prototype.hasOwnProperty.call(translations, language) || language === 'en') return html;

  if (typeof document !== 'undefined' && typeof document.createElement === 'function') {
    const template = document.createElement('template');
    template.innerHTML = html;
    const walker = document.createTreeWalker(template.content, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.parentElement?.closest('style,script,defs')) continue;
      node.nodeValue = translateText(node.nodeValue, language);
    }
    const elements = template.content.querySelectorAll('[placeholder],[title],[aria-label]');
    elements.forEach(el => {
      if (el.hasAttribute('placeholder')) {
        el.setAttribute('placeholder', translateText(el.getAttribute('placeholder'), language));
      }
      if (el.hasAttribute('title')) {
        el.setAttribute('title', translateText(el.getAttribute('title'), language));
      }
      if (el.hasAttribute('aria-label')) {
        el.setAttribute('aria-label', translateText(el.getAttribute('aria-label'), language));
      }
    });
    return template.innerHTML;
  }

  // SSR / Node.js fallback
  const protectedBlocks = [];
  const tokenized = html.replace(/<(style|script|defs)[^>]*>[\s\S]*?<\/\1>/gi, match => {
    protectedBlocks.push(match);
    return `___PROTECTED_BLOCK_${protectedBlocks.length - 1}___`;
  });

  const replaced = tokenized.replace(/>([^<]+)</g, (match, text) => {
    return `>${translateText(text, language)}<`;
  });

  return replaced.replace(/___PROTECTED_BLOCK_(\d+)___/g, (_, idx) => protectedBlocks[+idx]);
}

export default {
  translations,
  translateText,
  localizeHtml
};
